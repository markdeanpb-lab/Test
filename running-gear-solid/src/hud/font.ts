export const GLYPH_W = 5;
export const GLYPH_H = 7;

type Bits = boolean[][];
const CACHE = new Map<string, Bits>();

export function glyph(ch: string): Bits {
  const c = G[ch] ? ch : G[ch.toUpperCase()] ? ch.toUpperCase() : '?';
  let b = CACHE.get(c);
  if (!b) {
    b = G[c].map((row) => row.split('').map((p) => p === '#'));
    CACHE.set(c, b);
  }
  return b;
}

export const textWidth = (s: string, scale = 1, spacing = 1) =>
  s.length === 0 ? 0 : (s.length * (GLYPH_W + spacing) - spacing) * scale;

/** Draw text with pixel rectangles. Returns width. */
export function drawText(
  g: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  scale = 1,
  color = '#fff',
  spacing = 1,
) {
  g.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of s) {
    const b = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = b[r];
      let run = -1;
      for (let c = 0; c <= GLYPH_W; c++) {
        const on = c < GLYPH_W && row[c];
        if (on && run < 0) run = c;
        if (!on && run >= 0) {
          g.fillRect(cx + run * scale, cy + r * scale, (c - run) * scale, scale);
          run = -1;
        }
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
  return textWidth(s, scale, spacing);
}

/** Enumerate lit pixels of a string - used to build the 3D voxel logo. */
export function textPixels(s: string, spacing = 1): { x: number; y: number }[] {
  const out: { x: number; y: number }[] = [];
  let cx = 0;
  for (const ch of s) {
    const b = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++)
      for (let c = 0; c < GLYPH_W; c++) if (b[r][c]) out.push({ x: cx + c, y: r });
    cx += GLYPH_W + spacing;
  }
  return out;
}
